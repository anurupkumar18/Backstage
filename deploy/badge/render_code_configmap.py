"""Render badge-code.configmap.yaml: the simulator's Python packages as one zip.

The badge pods run the stock python:3.13-slim image with this zip on
PYTHONPATH, so no image build or registry is needed. The runtime uses only
the standard library. The zip is deterministic (sorted entries, fixed
timestamps, LF line endings), so the rendered file only changes when the code does.

    python deploy/badge/render_code_configmap.py           # rewrite the file
    python deploy/badge/render_code_configmap.py --check   # exit 1 if stale
"""

import argparse
import base64
import hashlib
import io
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "services" / "badge-simulator"
PACKAGES = ("badge_sim", "radar")
TARGET = Path(__file__).resolve().parent / "badge-code.configmap.yaml"


def bundle():
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for package in PACKAGES:
            for path in sorted((SOURCE / package).glob("*.py")):
                info = zipfile.ZipInfo(f"{package}/{path.name}", date_time=(1980, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = 0o644 << 16
                archive.writestr(info, path.read_bytes().replace(b"\r\n", b"\n"))
    return buffer.getvalue()


def render():
    data = bundle()
    digest = hashlib.sha256(data).hexdigest()[:16]
    return (
        "# Generated by deploy/badge/render_code_configmap.py. Do not edit by hand.\n"
        "apiVersion: v1\n"
        "kind: ConfigMap\n"
        "metadata:\n"
        "  name: badge-code\n"
        "  labels:\n"
        "    app.kubernetes.io/part-of: backstage\n"
        "    app.kubernetes.io/component: badge\n"
        "  annotations:\n"
        f"    backstage.dev/code-sha256: \"{digest}\"\n"
        "binaryData:\n"
        f"  badge-sim.zip: {base64.b64encode(data).decode()}\n"
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    current = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") if TARGET.exists() else ""
    if args.check:
        if current != content:
            print(f"{TARGET.name} is stale; run python deploy/badge/render_code_configmap.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_bytes(content.encode())
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(content)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
